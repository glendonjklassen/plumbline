/** The glyph for a plan's icon token; the flag for one this build cannot draw. */
export function planIconPath(icon: string | null | undefined): string {
  return PLAN_ICONS[icon ?? ""] ?? PLAN_ICONS.flag;
}

/** The palette role a colour token paints with: `rose` → `--planRose`, the
 *  camelCase the palette's wire names take on `<html>` (session.applyTheme). */
export function planColorVar(color: string): string {
  return `--plan${color.charAt(0).toUpperCase()}${color.slice(1)}`;
}

/** An inline `color:` for a plan surface — its chosen hue, or nothing, which
 *  leaves the surface's own gold. Every plan glyph fills with `currentColor`,
 *  so this one declaration recolours icon and accent together. */
export function planColorStyle(color: string | null | undefined): string {
  return color ? `color: var(${planColorVar(color)}, var(--gold, #9e7d38))` : "";
}
