//! Regenerate the committed C header (`include/plumbline.h`, the ABI reference)
//! from the `plumbline-ffi` C ABI:
//!
//! ```sh
//! cargo run -p plumbline-ffi --features bindgen --bin plumbline-bindgen
//! ```
//!
//! Feature-gated so a plain build never pulls host-only generators.

use std::path::Path;

fn main() {
    let crate_dir = env!("CARGO_MANIFEST_DIR");
    generate_c_header(crate_dir);
    println!("bindings regenerated.");
}

fn generate_c_header(crate_dir: &str) {
    let out = Path::new(crate_dir).join("include/plumbline.h");
    std::fs::create_dir_all(out.parent().unwrap()).expect("create include/");

    let config = cbindgen::Config {
        language: cbindgen::Language::C,
        pragma_once: true,
        cpp_compat: true, // wrap in extern "C" when compiled as C++
        documentation: true,
        documentation_style: cbindgen::DocumentationStyle::C99,
        header: Some(
            "/* Plumbline C ABI — GENERATED by `cargo run -p plumbline-ffi \
             --features bindgen`. Do not edit by hand. */"
                .to_string(),
        ),
        usize_is_size_t: true,
        export: cbindgen::ExportConfig {
            // `src/wasm.rs` is wasm32-only; cbindgen doesn't evaluate `cfg`, so its items are
            // excluded by name — extend this list when that module gains an export.
            exclude: [
                "plumbline_js_measure",
                "plumbline_web_alloc",
                "plumbline_web_free",
                "plumbline_web_measure_fnptr",
                "plumbline_engine_warm_step",
                "plumbline_engine_load_rnd_step",
                "plumbline_engine_defer_builds",
                "plumbline_engine_word_usage_blocks_json",
                "plumbline_engine_thread_blocks2_json",
            ]
            .iter()
            .map(|s| s.to_string())
            .collect(),
            ..Default::default()
        },
        ..Default::default()
    };

    cbindgen::Builder::new()
        .with_crate(crate_dir)
        .with_config(config)
        .generate()
        .expect("cbindgen: generate C header")
        .write_to_file(&out);
    println!("wrote {}", out.display());
}
